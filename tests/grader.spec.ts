import { describe, expect, it } from "vitest";
import { localGrade } from "../src/engine/grader";

describe("localGrade — локальная проверка ответа по значимым словам", () => {
  it("принимает ответ своими словами, если ключевые понятия совпадают", () => {
    const r = localGrade(
      "Что показывает команда whoami?",
      "Имя пользователя, под которым ты вошёл",
      "",
      "она печатает имя пользователя, под которым я сейчас работаю в системе",
    );
    expect(r.correct).toBe(true);
  });

  it("отклоняет пустой ответ", () => {
    const r = localGrade("Вопрос?", "Правильный ответ тут", "", "");
    expect(r.correct).toBe(false);
  });

  it("отклоняет ответ не по теме", () => {
    const r = localGrade(
      "Зачем нужен systemctl enable?",
      "включает автозапуск сервиса при загрузке сервера",
      "",
      "я люблю пиццу с ананасами по выходным",
    );
    expect(r.correct).toBe(false);
  });

  it("засчитывает совпадение с однокоренными словами (лёгкий стемминг)", () => {
    const r = localGrade(
      "Зачем nano?",
      "чтобы редактировать текстовые файлы прямо в терминале",
      "",
      "чтобы отредактировать текстовый файл, не выходя из терминала",
    );
    expect(r.correct).toBe(true);
  });

  it("feedback содержит правильный ответ, даже если игрок ошибся", () => {
    const r = localGrade("Вопрос?", "уникальная правильная формулировка", "доп. пояснение", "мимо");
    expect(r.feedback).toContain("уникальная правильная формулировка");
  });
});
