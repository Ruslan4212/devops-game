#!/bin/bash
# Собирает index.html из частей. Порядок важен: данные -> состояние -> движки -> запуск.
set -euo pipefail
cd "$(dirname "$0")"

PARTS=(
  p1.txt   # разметка страницы и стили
  p2.txt   # ядро симулятора терминала: виртуальная ФС, парсер, базовые команды
  p3.txt   # команды docker, kubectl, git, terraform, ansible
  p6.txt   # миры, дорожная карта, бейджи (базовый набор)
  p7.txt   # дополнительные миссии
  p10.txt  # миссии и план по программе «DevOps: Junior»
  p11.txt  # миссии по модулям курса Linux
  p4.txt   # лаборатории: linux, сети, git, docker
  p5.txt   # лаборатории: ci/cd, iac, k8s, sre + песочница
  p12.txt  # миссии Git и GitLab CI + лаборатория с git bisect
  p8.txt   # состояние, сохранение, экраны карты и плана
  p13.txt  # тренажёр команд
  p14.txt  # персонаж, навыки, карьера, сюжет
  p15.txt  # экраны персонажа и карьеры, события новых слоёв
  p9.txt   # раннер миссий и лабораторий, песочница, запуск приложения
)

cat "${PARTS[@]}" > index.html
echo "index.html собран: $(wc -c < index.html) байт"
