/**
 * Экранирует спецсимволы, чтобы текст, введённый игроком, искался буквально.
 * Вынесено отдельно: и `grep`, и `find` строят RegExp из пользовательского ввода,
 * а ошибка в экранировании ломает обе команды разом.
 */
export function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
