import { mkdirp, writeFile } from "../engine/vfs";
import { has, ran } from "../missions/helpers";
import type { Lesson, World } from "../engine/types";

const DOCKERFILE = 'FROM node:20-alpine\nWORKDIR /app\nCOPY . .\nCMD ["node","index.js"]\n';

/** Папка приложения без Dockerfile. */
function seedApp(w: World): void {
  mkdirp(w, "/home/devops/app");
  writeFile(w, "/home/devops/app/index.js", "console.log('магазин слушает порт 80');\n");
  writeFile(w, "/home/devops/app/package.json", '{ "name": "shop", "version": "1.0.0" }\n');
  w.cwd = "/home/devops/app";
}

/** Приложение с готовым Dockerfile. */
function seedWithDockerfile(w: World): void {
  seedApp(w);
  writeFile(w, "/home/devops/app/Dockerfile", DOCKERFILE);
}

/** Приложение, где образ уже собран. */
function seedWithImage(w: World): void {
  seedWithDockerfile(w);
  w.docker.images.push({ tag: "shop:1.0", layers: 4 });
}

/** Приложение с собранным образом и запущенным контейнером. */
function seedWithContainer(w: World): void {
  seedWithImage(w);
  w.docker.containers.push({
    name: "web",
    image: "shop:1.0",
    state: "running",
    hostPort: 8080,
    cPort: 80,
    logs: ["Starting server on :80", "listening"],
  });
}

