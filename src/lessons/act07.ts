/** Репозиторий с привязанным сервером и одним коммитом. */
function seedRepo(w: World): void {
  mkdirp(w, "/home/devops/app/src");
  mkdirp(w, "/home/devops/app/.github/workflows");
  writeFile(w, "/home/devops/app/index.js", "console.log('магазин');\n");
  writeFile(w, "/home/devops/app/src/sum.js", "function sum(a, b) {\n  return a + b;\n}\n");
  w.cwd = "/home/devops/app";
  w.git = {
    branch: "main",
    branches: ["main"],
    staged: [],
    commits: [{ msg: "первый коммит", files: ["index.js"], branch: "main", hash: "a1b2c3d" }],
    remote: "git@github.com:shop/app.git",
    pushed: 1,
  };
}

