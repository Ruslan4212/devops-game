const isExec =
  (path: string) =>
  (w: World): boolean => {
    const n = getNode(w, path);
    return !!n && n.type === "file" && /x/.test(n.mode.slice(0, 3));
  };

/** Готовый рабочий скрипт для показа. */
function seedExample(w: World): void {
  writeFile(w, "/home/devops/hello.sh", "#!/bin/bash\necho Привет из скрипта\nls\n");
  const n = getNode(w, "/home/devops/hello.sh");
  if (n && n.type === "file") n.mode = "rwxr-xr-x";
}

