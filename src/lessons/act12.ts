/** Prometheus уже настроен (Акт 11), каталог Grafana пуст. */
function seedGrafana(w: World): void {
  mkdirp(w, "/home/devops/grafana");
  w.cwd = "/home/devops/grafana";
  w.prom = {
    exporters: { 9100: "node", 8080: "app" },
    targets: [
      { job: "node", instance: "localhost:9100", up: true },
      { job: "app", instance: "localhost:8080", up: true },
    ],
    configLoaded: true,
    rulesLoaded: true,
  };
  w.grafana = { datasources: [], dashboards: [] };
}

/** То же, но источник данных уже подключён. */
function seedWithDs(w: World): void {
  seedGrafana(w);
  writeFile(w, "/home/devops/grafana/datasources.yml", DS_OK);
  w.grafana!.datasources = ["Prometheus"];
}

/** Источник подключён И дашборд уже загружен — чтобы  grafana render  было что рисовать. */
function seedWithDash(w: World): void {
  seedWithDs(w);
  writeFile(w, "/home/devops/grafana/dashboard.json", DASH_OK);
  w.grafana!.dashboards = [
    {
      title: "shop-api",
      panels: [
        { title: "Запросы в секунду", expr: "rate(http_requests_total[5m])", unit: "reqps" },
        {
          title: "Ошибки 5xx",
          expr: 'rate(http_requests_total{status="500"}[5m])',
          unit: "reqps",
        },
        {
          title: "p95 задержки",
          expr: "histogram_quantile(0.95, rate(http_request_duration_seconds_bucket[5m]))",
          unit: "s",
        },
        { title: "Цели опрашиваются", expr: "up", unit: "" },
      ],
    },
  ];
}

