import type { Lesson, QuizStep } from "../engine/types";

/**
 * Экзамен акта — отдельный урок из одних вопросов, выстроенных по возрастанию
 * сложности `d` (1 «вспомни» → 7 «разбери инцидент под давлением»). Формат тот же,
 * что у обычных вопросов: ошибся — объяснение и следующий вопрос, застрять нельзя.
 * XP за экзамен ощутимо выше рядового урока — это контрольная точка темы.
 */
interface ExamQ {
  d: number;
  text: string;
  options: string[];
  answer: number;
  explain: string;
}

function buildExam(act: number, topic: string, qs: readonly ExamQ[]): Lesson {
  const sorted = [...qs].sort((a, b) => a.d - b.d);
  const steps: Lesson["steps"] = [
    {
      kind: "say",
      text:
        `Экзамен по теме «${topic}».\n\n` +
        `${sorted.length} вопросов, от простого к сложному: первые — «вспомни определение»,\n` +
        `последние — «ты дежурный, инцидент, твой первый шаг». Провалить нельзя:\n` +
        `на каждый ответ будет разбор.`,
    },
    ...sorted.map<QuizStep>((q) => ({
      kind: "quiz",
      d: q.d,
      text: q.text,
      options: [...q.options],
      answer: q.answer,
      explain: q.explain,
    })),
    {
      kind: "say",
      text:
        `Экзамен акта ${act} пройден. Если какой-то вопрос дался тяжело — вернись\n` +
        `к соответствующему уроку акта, теория там разобрана пошагово.`,
    },
  ];
  return {
    id: `экз${act}`,
    act,
    title: `Экзамен акта ${act}: ${topic}`,
    intro: `Контрольная по акту ${act}. ${sorted.length} вопросов по возрастанию сложности.`,
    xp: 12 + sorted.length * 3,
    steps,
  };
}

