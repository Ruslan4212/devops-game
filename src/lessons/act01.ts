/** В домашней папке: notes.txt + README.md + папка work. */
function seedHome(w: World): void {
  writeFile(w, "/home/devops/README.md", "# Магазин\nСервис приёма заказов.\n");
  const home = getNode(w, "/home/devops");
  if (home && home.type === "dir" && !home.children["work"]) home.children["work"] = dir();
  writeFile(
    w,
    "/home/devops/notes.txt",
    "Первый рабочий день.\nДали доступ к серверу.\nГлавное правило: ничего не сломать.\n",
  );
}

const lastCmd = (w: World): string => (w.log.length ? w.log[w.log.length - 1].cmd.trim() : "");
const ranOK = (w: World, re: RegExp): boolean => w.log.some((l) => re.test(l.cmd) && l.code === 0);

