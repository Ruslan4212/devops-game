/** Папка проекта с парой файлов. */
function seedProject(w: World): void {
  mkdirp(w, "/home/devops/app");
  writeFile(w, "/home/devops/app/index.js", "console.log('магазин запущен');\n");
  writeFile(w, "/home/devops/app/README.md", "# Магазин\nСервис приёма заказов.\n");
  w.cwd = "/home/devops/app";
}

/** Проект, где уже есть репозиторий и один коммит. */
