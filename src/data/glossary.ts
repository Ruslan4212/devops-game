export interface GlossaryRow {
  /** к какой команде относится ряд ("общее" для операторов) */
  cmd: string;
  /** сам токен: имя команды, флаг или подкоманда */
  tok: string;
  /** объяснение */
  d: string;
  /** ряд-заголовок команды */
  head?: boolean;
  /** ряд флага (для стилизации) */
  flag?: boolean;
}

/**
 * Поиск по глоссарию.
 *   пустой запрос  — только заголовки всех команд (браузируемый указатель);
 *   непустой запрос — заголовок команды, если имя совпало, плюс все флаги,
 *                     подкоманды и операторы, где встречаются ВСЕ слова запроса.
 * Возвращает не более 200 рядов.
 */
export function searchGlossary(q: string): GlossaryRow[] {
  const words = (q || "").toLowerCase().trim().split(/\s+/).filter(Boolean);
  const rows: GlossaryRow[] = [];
  const hay = (...parts: string[]): string => parts.join(" ").toLowerCase();

  for (const [cmd, info] of Object.entries(GLOSSARY.commands)) {
    if (!words.length) {
      rows.push({ cmd, tok: cmd, d: info.d, head: true });
      continue;
    }
    if (words.some((w) => cmd.includes(w))) rows.push({ cmd, tok: cmd, d: info.d, head: true });
    for (const [k, v] of Object.entries(info.sub ?? {})) {
      const h = hay(cmd, k, v);
      if (words.every((w) => h.includes(w))) rows.push({ cmd, tok: k, d: v });
    }
    for (const [k, v] of Object.entries(info.f ?? {})) {
      const h = hay(cmd, k, v);
      if (words.every((w) => h.includes(w))) rows.push({ cmd, tok: k, d: v, flag: true });
    }
  }

  if (words.length) {
    for (const [k, v] of Object.entries(GLOSSARY.general)) {
      const h = hay(k, v);
      if (words.every((w) => h.includes(w))) rows.push({ cmd: "общее", tok: k, d: v });
    }
  }

  return rows.slice(0, 200);
}
